-- 19,406건을 전량 생성한 뒤에 추가하려면 전량 재생성이라 약 27만원이 든다. 13배 차이라
-- 이 테이블에서는 "쓸지 안 쓸지 애매하면 지금 넣는다" 가 맞는 판단이 된다.
