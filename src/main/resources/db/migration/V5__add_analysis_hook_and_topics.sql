-- SNS 게시물 첫 줄 / 카드뉴스 표지 / 레터 소제목으로 그대로 쓰는 한 문장.
--
-- 법안명이 아니라 내용 핵심어를 담는다. 법안명 길이를 재보면 중앙값 16자, p90 32자,
-- 최대 99자여서 40자 안에 법안명과 서술을 함께 넣는 것이 296건에서 산술적으로 불가능하다.
-- 게다가 "도로교통법 개정" 보다 "어린이통학버스" 가 독자에게 정보량이 크다.
ALTER TABLE bill_analysis ADD COLUMN hook TEXT;

-- 주제 태그. 국회 원천 데이터에는 주제 분류가 아예 없어 우리가 만들어야 한다.
--
-- committee_name 으로 대신할 수 없다. 법제사법위원회(1,822건)는 주제가 아니라 모든 법안이
-- 거쳐가는 관문이고, 행정안전위원회(2,655건)는 지방자치·경찰·재난·개인정보가 뒤섞여 있다.
--
-- 값은 BillTopic 의 16개 어휘로만 제한한다. 그 제약을 DB CHECK 가 아니라 애플리케이션에
-- 둔 이유는 어휘를 늘릴 때마다 마이그레이션을 강제하지 않기 위해서다. 어휘 변경은
-- prompt_version 을 올리는 사건이지 스키마 변경이 아니다.
--
-- 어느 어휘에도 맞지 않으면 빈 배열로 둔다. '기타' 를 만들지 않는 이유는 그것이
-- 곧 최다 태그가 되면서 분류 자체가 무의미해지기 때문이다.
ALTER TABLE bill_analysis ADD COLUMN topics JSONB NOT NULL DEFAULT '[]'::jsonb;

-- 레터 편집("이번 달 환경 법안")과 앱 필터가 태그로 조회한다.
-- JSONB 배열 포함 검사(@>)는 GIN 없이는 전체 스캔이다.
CREATE INDEX idx_bill_analysis_topics ON bill_analysis USING gin (topics);
