-- =============================================================================
-- V3. bill.status 에 MERGED(대안반영) 추가
--
-- 배경:
-- 인증키를 받아 실제 국회 API 응답을 확인한 결과, 처리된 법안 중 가장 큰 덩어리가
-- '대안반영폐기'(표본 기준 처리 건의 약 21%)였다.
--
-- 이것은 비슷한 법안 여러 건을 위원회가 하나의 '대안'으로 묶으면서 원 법안들을
-- 형식적으로 폐기하는 절차다. 법안 자체는 폐기되지만 그 내용은 대안에 담겨 법이 된다.
--
-- 따라서 PASSED 로 분류하면 사실과 다르고(이 법안은 통과하지 않았다),
-- DISCARDED 로 분류하면 "발의자의 노력이 무산됐다" 는 잘못된 인상을 준다.
-- 별도 상태로 두는 편이 정확하다.
--
-- 이미 적용된 V1 을 수정하지 않고 새 버전으로 추가한다 (Flyway 체크섬 원칙).
-- =============================================================================

ALTER TABLE bill DROP CONSTRAINT ck_bill_status;

ALTER TABLE bill ADD CONSTRAINT ck_bill_status
    CHECK (status IN ('PENDING', 'PASSED', 'MERGED', 'DISCARDED', 'UNKNOWN'));
