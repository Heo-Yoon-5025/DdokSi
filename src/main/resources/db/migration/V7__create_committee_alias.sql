-- =============================================================================
-- V7. committee_alias : 개편 전후로 갈라진 위원회 이름을 하나로 묶는다
--
-- 문제:
-- 22대 국회 중간 상임위 개편으로 같은 위원회가 두 이름으로 존재한다. 심사가 끝난 법안은
-- 당시 이름이 기록에 얼어붙었고, 아직 열려 있는 법안만 새 이름으로 옮겨갔다.
-- 원천 데이터 어디에도 둘이 같은 위원회라는 표시가 없다.
--
-- 실측(2026-09-20, 19,447건):
--   distinct 위원회명 25개 = 상임위 20 + 특별위원회 5. 통합 후 정식 이름 22개.
--
--   기획재정위원회      439건 (PENDING 0)  →  재정경제기획위원회        1,432건
--   환경노동위원회      145건 (PENDING 0)  →  기후에너지환경노동위원회  1,763건
--   여성가족위원회       38건 (PENDING 0)  →  성평등가족위원회            219건
--
-- 판별 근거는 "PENDING 이 0건" 이지만, 그것만으로는 부족하다. 특별위원회 5개도 PENDING 이
-- 0건인데 그쪽은 이름이 바뀐 게 아니라 활동 기한이 끝난 한시 조직이다(기후위기 특별위원회,
-- 정치개혁특별위원회, 산불피해지원대책 특별위원회 등). 정확한 규칙은
-- "상임위원회 중 PENDING 이 0건" 이다. 특위는 통합 대상이 아니다.
--
-- 왜 지금 해야 하는가:
-- 앱에서는 옛 법안이 안 보이는 정도로 끝나지만, 레터에서는 조용한 실패가 된다. 구독자가
-- 구 이름을 고르면 매칭되는 PENDING 법안이 0건이라 매달 빈 호를 받고 어디에도 에러가
-- 남지 않는다. 그리고 committee_name 을 읽는 곳은 지금 둘(조회 API, 앱 필터)뿐이지만
-- 구독·레터가 붙으면 다섯, 여섯이 된다. 고칠 자리가 적을 때 고치는 편이 싸다.
--
-- 왜 bill.committee_name 을 직접 갱신하지 않는가:
-- 그 값은 국회가 내려준 사실이다. 그 법안은 실제로 '환경노동위원회' 시절에 처리됐고,
-- 덮어쓰면 그 사실이 사라진다. 수집 배치가 같은 값을 다시 내려주므로 매번 되돌려야 하는
-- 문제도 생긴다. 원본은 두고 조회 시점에 묶는다.
--
-- 왜 정규화 컬럼이 아니라 별칭 테이블인가:
-- 개편은 반복되는 사건이지 일회성 사고가 아니다. 다음 개편 때 이 테이블은 행 하나를
-- 추가하면 끝나지만, 컬럼 방식은 마이그레이션에 19,447건 백필이 따라붙는다.
-- 위원회에 소개문이나 대표 주제 같은 것을 붙이고 싶어질 때 자리가 생기기도 한다.
-- =============================================================================

CREATE TABLE committee_alias (
    -- 기록에 남아 있는 옛 이름. 조회 키라서 PK 로 둔다 — 한 옛 이름이 두 위원회를
    -- 가리키는 일은 있을 수 없다.
    alias_name     VARCHAR(100) PRIMARY KEY,

    -- 지금 쓰는 정식 이름. 앱 필터와 구독 설정에 노출되는 쪽이다.
    canonical_name VARCHAR(100) NOT NULL,

    -- 근거를 남긴다. 몇 년 뒤 "이건 왜 묶여 있지?" 가 반드시 나온다.
    note           TEXT,

    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- 자기 자신을 가리키면 조회가 무한히 맴돈다.
    CONSTRAINT ck_committee_alias_not_self CHECK (alias_name <> canonical_name)
);

-- canonical_name → alias_name 역방향 조회(필터 확장)가 주 경로다.
CREATE INDEX idx_committee_alias_canonical ON committee_alias (canonical_name);

-- -----------------------------------------------------------------------------
-- 22대 중간 개편 3쌍.
--
-- 체인(A→B, B→C)을 만들지 않는다. canonical_name 은 반드시 별칭이 아닌 최종 이름이어야
-- 한다. DB 제약으로는 자기참조까지만 막을 수 있으므로 이 규칙은 여기 적어 둔다.
-- 개편이 또 일어나 새 이름이 생기면, 기존 행들의 canonical_name 도 함께 새 이름으로
-- 갱신해야 한다 — 행을 추가하는 것만으로는 체인이 된다.
-- -----------------------------------------------------------------------------
